# ============================================================

def ud_set1(sigma, dt):
    u = np.exp(sigma * np.sqrt(dt))
    d = np.exp(-sigma * np.sqrt(dt))
    return u, d

def ud_set2(sigma, r, dt):
    u = np.exp(sigma * np.sqrt(dt) + (r - 0.5 * sigma**2) * dt)
    d = np.exp(-sigma * np.sqrt(dt) + (r - 0.5 * sigma**2) * dt)
    return u, d

def european_binomial_price(S0, K, T, r, sigma, M, u, d):
    dt = T / M
    p = (np.exp(r * dt) - d) / (u - d)

    ST = np.array([S0 * (u**j) * (d**(M - j)) for j in range(M + 1)])
    call = np.maximum(ST - K, 0)
    put  = np.maximum(K - ST, 0)

    for _ in range(M):
        call = np.exp(-r * dt) * (p * call[1:] + (1 - p) * call[:-1])
        put  = np.exp(-r * dt) * (p * put[1:]  + (1 - p) * put[:-1])

    return call[0], put[0]

