def lookback_markov(S0, T, r, sigma, M):
    dt = T / M
    u, d = ud_set2(sigma, r, dt)

    states = {(0, S0): 1.0}
    for t in range(1, M+1):
        new_states = {}
        for (k, mx), prob in states.items():
            Su = S0 * (u**(k+1)) * (d**(t-k-1))
            Sd = S0 * (u**k) * (d**(t-k))

            mu, md = max(mx, Su), max(mx, Sd)
            new_states[(k+1, mu)] = new_states.get((k+1, mu), 0) + prob
            new_states[(k, md)]   = new_states.get((k, md), 0) + prob

        states = new_states

    payoff = 0
    for (k, mx), prob in states.items():
        ST = S0 * (u**k) * (d**(M-k))
        payoff += prob * (mx - ST)

    return np.exp(-r*T) * payoff

