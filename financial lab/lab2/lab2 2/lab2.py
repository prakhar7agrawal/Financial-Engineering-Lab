print("NOTE: Basic binomial is exponential. Using small M only.\n")

def lookback_basic(S0, T, r, sigma, M):
    dt = T / M
    u = np.exp(sigma*np.sqrt(dt) + (r - 0.5*sigma**2)*dt)
    d = np.exp(-sigma*np.sqrt(dt) + (r - 0.5*sigma**2)*dt)
    p = (np.exp(r*dt) - d) / (u - d)

    paths = [(S0, S0)]
    for _ in range(M):
        new_paths = []
        for price, mx in paths:
            new_paths.append((price*u, max(mx, price*u)))
            new_paths.append((price*d, max(mx, price*d)))
        paths = new_paths

    payoff = np.array([mx - price for price, mx in paths])
    probs = np.array([
        p**bin(i).count("1") * (1-p)**(M - bin(i).count("1"))
        for i in range(len(payoff))
    ])

    return np.exp(-r*T) * np.sum(payoff * probs)

