import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.optimize import minimize

# Load CSV
data = pd.read_csv("stocks.csv", index_col=0)

# Compute returns
returns = data.pct_change().dropna()

# Annualized mean & covariance
mu = returns.mean() * 252
C = returns.cov() * 252
n = len(mu)

# Helper functions
def port_return(w):
    return np.dot(w, mu)

def port_risk(w):
    return np.sqrt(w.T @ C @ w)

bounds = [(0,1)] * n
sum_constraint = {'type': 'eq', 'fun': lambda w: np.sum(w) - 1}

# -------------------------------------------------
# (A) Efficient Frontier
# -------------------------------------------------
target_returns = np.linspace(mu.min(), mu.max(), 100)
risks = []

for R in target_returns:
    constraints = [
        sum_constraint,
        {'type': 'eq', 'fun': lambda w, R=R: port_return(w) - R}
    ]

    res = minimize(
        lambda w: w.T @ C @ w,
        np.ones(n)/n,
        bounds=bounds,
        constraints=constraints
    )

    risks.append(np.sqrt(res.fun))

plt.plot(risks, target_returns)
plt.xlabel("Risk")
plt.ylabel("Return")
plt.title("Efficient Frontier")
plt.grid()
plt.show()

# -------------------------------------------------
# (B) Market Portfolio (rf = 5%)
# -------------------------------------------------
rf = 0.05

def neg_sharpe(w):
    return -(port_return(w) - rf) / port_risk(w)

res = minimize(
    neg_sharpe,
    np.ones(n)/n,
    bounds=bounds,
    constraints=[sum_constraint]
)

w_m = res.x
ret_m = port_return(w_m)
risk_m = port_risk(w_m)

print("\nMarket Portfolio Weights:")
print(pd.Series(w_m, index=mu.index))

# -------------------------------------------------
# (C) Capital Market Line
# -------------------------------------------------
x = np.linspace(0, risk_m * 1.5, 100)
y = rf + (ret_m - rf)/risk_m * x

plt.plot(x, y)
plt.xlabel("Risk")
plt.ylabel("Return")
plt.title("Capital Market Line")
plt.grid()
plt.show()

# -------------------------------------------------
# (D) Security Market Line
# -------------------------------------------------
beta = (C @ w_m) / (w_m.T @ C @ w_m)
capm_returns = rf + beta * (ret_m - rf)

plt.scatter(beta, mu)
plt.plot(beta, capm_returns)
plt.xlabel("Beta")
plt.ylabel("Expected Return")
plt.title("Security Market Line")
plt.grid()
plt.show()

